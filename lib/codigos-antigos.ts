const RE_REF = /\b(C\d{3}B[0-9A-Z]{2,4}|KIT\d{4,6}|CB-[A-Z]{2}\d{2,4}[A-Z]?)\b/gi;

/** Referências antigas citadas num texto, com o código CB e o nome atual (as que não estão na tabela vêm com cb vazio). */
export function refsAntigas(texto: string): { antigo: string; cb: string; nome: string }[] {
  const vistos = new Set<string>();
  const out: { antigo: string; cb: string; nome: string }[] = [];
  for (const m of String(texto || "").matchAll(RE_REF)) {
    const k = m[1].toUpperCase();
    if (vistos.has(k)) continue;
    vistos.add(k);
    const r = CODIGOS_ANTIGOS[k];
    out.push({ antigo: k, cb: r ? r.cb : "", nome: r ? r.nome : "" });
  }
  return out;
}

/** Linha pronta para avisos: "C186B390 = CB127 Garrafa Térmica Inox 450ml". */
export function textoRefs(texto: string): string {
  return refsAntigas(texto).map((r) => (r.cb ? `${r.antigo} = ${r.cb} ${r.nome}` : `${r.antigo} (código antigo sem correspondência: conferir)`)).join(" · ");
}
